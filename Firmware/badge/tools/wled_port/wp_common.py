def sha256(path):
    with open(path, "rb") as f:
        return hashlib.sha256(f.read()).hexdigest()


def load_manifest():
    with open(MANIFEST, encoding="utf-8") as f:
        return json.load(f)


def write_if_changed(path, text):
    """Write text (utf-8, \\n) only when it differs, so mtimes stay put and reruns are no-ops."""
    os.makedirs(os.path.dirname(path), exist_ok=True)
    data = text.encode("utf-8")
    if os.path.exists(path):
        with open(path, "rb") as f:
            if f.read() == data:
                return False
    with open(path, "wb") as f:
        f.write(data)
    return True


# ------------------------------------------------------------------ community effects (wledport add)
# Each components/wled_fx/community/<slug>.cpp starts with "// wledport-add: key=value; ..." lines and ends
# with a registration struct. The files are the source of truth; the registry header, the CMake source list
# and the manifest's COMMUNITY entries are derived from them here (by add, remove and import).
COMMUNITY_DIR = os.path.join(COMPONENT_DIR, "community")
COMMUNITY_H = os.path.join(COMMUNITY_DIR, "wled_fx_community.h")
COMMUNITY_CMAKE = os.path.join(COMMUNITY_DIR, "community.cmake")


def community_scan():
    out = []
    if not os.path.isdir(COMMUNITY_DIR):
        return out
    for fn in sorted(os.listdir(COMMUNITY_DIR)):
        if not fn.endswith(".cpp"):
            continue
        meta = {}
        with open(os.path.join(COMMUNITY_DIR, fn), encoding="utf-8") as f:
            for line in f:
                if line.startswith("// wledport-add:"):
                    for kv in line[len("// wledport-add:"):].split(";"):
                        k, _, v = kv.strip().partition("=")
                        if k:
                            meta[k] = v.strip()
        if "name" in meta and "fn" in meta:
            meta["file"] = "community/" + fn
            meta["slug"] = fn[:-4]
            out.append(meta)
    return out


def community_sync(man, mode_count):
    """Give community effects ids mode_count, mode_count+1, ... (appended after the stock table, so
    addEffect() pushes them back in this order), rewrite the registry header + CMake list, and replace
    the manifest's COMMUNITY entries. Returns the number of files changed (manifest not written here)."""
    ents = community_scan()
    if mode_count is None:
        raise SystemExit("community: manifest has no mode_count (re-run wledport.py import)")
    if mode_count + len(ents) > 255:
        raise SystemExit("community: effect ids would exceed 254")
    c_str = lambda s: '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'
    h = ["// SPDX-License-Identifier: EUPL-1.2\n",
         "// Generated by tools/wled_port/wledport.py add/remove - do not edit. One row per community/*.cpp:\n",
         "// X(fx id, name, registration symbol). Ids follow the stock table (MODE_COUNT) in file name order.\n",
         "#pragma once\n#define WLED_FX_COMMUNITY(X)"]
    cm = ["# SPDX-License-Identifier: EUPL-1.2\n# Generated by tools/wled_port/wledport.py add/remove - do not edit\n",
          "set(wled_fx_community_srcs"]
    effects = [e for e in man["effects"] if e.get("bucket") != "COMMUNITY"]
    for i, e in enumerate(ents):
        fid = mode_count + i
        h.append(f" \\\n  X({fid}, {c_str(e['name'])}, wled_fx_comm_{e['slug']})")
        cm.append(f"\n    {e['file']}")
        effects.append(dict(id=fid, sym=None, fn=e["fn"], name=e["name"], bucket="COMMUNITY", compiled=True,
                            included=True, file=e["file"], source=e.get("source", ""),
                            licence=e.get("licence", ""), added=e.get("added", "")))
    h.append("\n")
    cm.append(")\n")
    man["effects"] = effects
    man["counts"]["community"] = len(ents)
    man["counts"]["included"] = sum(1 for e in effects if e["included"])
    changed = write_if_changed(COMMUNITY_H, "".join(h))
    changed += write_if_changed(COMMUNITY_CMAKE, "".join(cm))
    return changed


def save_manifest(man):
    return write_if_changed(MANIFEST, json.dumps(man, indent=1) + "\n")


def require_git_ignored(path, what):
    """Household data (strip IP, preset names, menu rows) must never land in a committable path.
    git check-ignore: 0 = ignored, 1 = NOT ignored (refuse), 128 = outside any repo (fine)."""
    import subprocess
    ap = os.path.abspath(path)
    d = os.path.dirname(ap)
    while d and not os.path.isdir(d):
        d = os.path.dirname(d)
    try:
        rc = subprocess.run(["git", "check-ignore", "-q", ap], cwd=d, capture_output=True).returncode
    except OSError:
        return  # ponytail: no git, nothing to commit it with either
    if rc == 1:
        raise SystemExit(f"{what}: {path} is not git-ignored and would hold household data.\n"
                         "  Use wled_snapshot/<name> or wled_presets*.json inside Firmware/badge (see its .gitignore).")
