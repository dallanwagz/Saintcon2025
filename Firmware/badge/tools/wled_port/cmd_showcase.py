"""wledport showcase - pick the effects worth browsing on the badge and a setup that makes each one visible.

Renders every available effect on the host (same wled_fx sources as the badge) at the badge's 20 LEDs with
its WLED metadata defaults, scores brightness and motion, and if the defaults are dark or frozen tries a few
fallback palettes/colours. Effects that never come alive are left out. Writes a C table the LEDs app browses:
components/wled_mirror/include/wled_showcase_gen.h (generated, committed).
"""
import os
import re
import subprocess

from wp_common import BADGE_DIR, HOST_DIR

HELP = "score every effect on 20 LEDs and regenerate the LEDs-app showcase table"

SIM = os.path.join(HOST_DIR, "out", "wledsim")
OUT = os.path.join(BADGE_DIR, "components", "wled_mirror", "include", "wled_showcase_gen.h")
FRAMES, WARMUP = 300, 50          # 12 s at the badge's 40 ms frame
DEFAULT_COL = "FFA000,000000,000000"  # WLED's power-on colours (orange, black, black)
# Fallbacks, in order: (palette, colours). 6 = Party, 11 = Rainbow (WLED built-ins).
FALLBACKS = [(None, "00B4FF,FF0050,FFC800"), (6, None), (11, None), (11, "00B4FF,FF0050,FFC800")]
MIN_BRIGHT, MIN_LIT, MIN_MOTION = 14.0, 0.15, 3.0
STRIDE = 25  # frames = 1 s


def add_args(p):
    p.add_argument("--dry-run", action="store_true", help="print the scores, do not write the header")
    p.add_argument("-v", action="store_true", help="print every effect's score")


def render(fx, pal=None, col=None, base=None):
    cmd = [SIM, str(fx)]
    if pal is not None or base:
        b = base or {}
        cmd += [str(pal if pal is not None else b["pal"]), str(b["sx"]), str(b["ix"]), str(b["c1"]), str(b["c2"]), str(b["c3"])]
    cmd += ["--frames", str(FRAMES), "--ms", "40", "--seed", "1", "--col", col or DEFAULT_COL]
    out = subprocess.run(cmd, capture_output=True, text=True, check=True).stdout.splitlines()
    m = re.match(r"# fx\s+(\d+) \((.*)\) pal (\d+) sx (\d+) ix (\d+) c1 (\d+) c2 (\d+) c3 (\d+)", out[0])
    head = dict(zip(["fx", "name", "pal", "sx", "ix", "c1", "c2", "c3"], m.groups()))
    frames = [bytes.fromhex(l.split()[-1]) for l in out[1:] if l.startswith("t=")]
    return head, frames[WARMUP:]


def score(frames):
    n = len(frames[0]) // 3
    bright = lit = motion = 0.0
    for f in frames:
        for i in range(n):
            v = max(f[3 * i], f[3 * i + 1], f[3 * i + 2])
            bright += v
            lit += v > 24
    # motion: frames 1 s apart, so slow effects (Random Colors, Sweep Random) count as moving
    pairs = list(zip(frames, frames[STRIDE:]))
    for a, b in pairs:
        motion += sum(abs(x - y) for x, y in zip(a, b)) / (3 * n)
    cnt = len(frames) * n
    return bright / cnt, lit / cnt, motion / max(1, len(pairs))


def alive(s):
    return s[0] >= MIN_BRIGHT and s[1] >= MIN_LIT and s[2] >= MIN_MOTION


def run(args):
    if not os.path.exists(SIM):
        subprocess.check_call(["make", "-C", HOST_DIR, "out/wledsim"])
    ids = [int(l.split()[1]) for l in subprocess.run([SIM, "--list"], capture_output=True, text=True).stdout.splitlines()
           if l.startswith("fx ")]
    keep, dropped = [], []
    for fx in ids:
        head, fr = render(fx)
        s, pal, col = score(fr), None, None
        if not alive(s):
            for fpal, fcol in FALLBACKS:
                _, fr2 = render(fx, fpal, fcol, head)
                s2 = score(fr2)
                if alive(s2):
                    s, pal, col = s2, fpal, fcol
                    break
        line = f"fx {fx:3} {head['name']:<22} bright {s[0]:6.1f} lit {s[1]:.2f} motion {s[2]:6.2f}"
        if alive(s):
            keep.append((fx, head["name"], pal, col))
            if args.v:
                print("keep", line, f"pal={pal}" if pal is not None else "", f"col={col}" if col else "")
        else:
            dropped.append(head["name"])
            if args.v:
                print("DROP", line)
    keep.sort(key=lambda k: k[1].lower())
    print(f"showcase: {len(keep)} of {len(ids)} effects come alive on 20 LEDs; dropped {len(dropped)}: {', '.join(dropped)}")
    if args.dry_run:
        return 0

    def rgb(c):
        return "{" + ", ".join("{%d, %d, %d}" % tuple(bytes.fromhex(x)) for x in c.split(",")) + "}"

    rows = []
    for fx, name, pal, col in keep:
        rows.append("    {%3d, %3d, %d, %s}, // %s" % (fx, 255 if pal is None else pal, 1 if col else 0,
                                                     rgb(col) if col else "{{0}}", name))
    with open(OUT, "w") as f:
        f.write("// SPDX-License-Identifier: EUPL-1.2\n")
        f.write("// Generated by tools/wled_port/wledport.py showcase - do not edit. Effects that visibly animate on the\n")
        f.write("// badge's 20 LEDs, sorted by name, with the palette / colours that make them do so (255 = keep the\n")
        f.write("// effect's default palette; has_col = 0 keeps WLED's default colours).\n#pragma once\n#include <stdint.h>\n\n")
        f.write("typedef struct { uint8_t fx, pal, has_col; uint8_t col[3][3]; } wled_showcase_t;\n\n")
        f.write("static const wled_showcase_t WLED_SHOWCASE[] = {\n" + "\n".join(rows) + "\n};\n")
        f.write("#define WLED_SHOWCASE_COUNT (int)(sizeof(WLED_SHOWCASE) / sizeof(WLED_SHOWCASE[0]))\n")
    print("wrote", os.path.relpath(OUT, BADGE_DIR))
    return 0
