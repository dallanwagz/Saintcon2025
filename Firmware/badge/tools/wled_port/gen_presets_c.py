#!/usr/bin/env python3
"""Turn the local WLED preset table (JSON, see wled_presets.example.json) into the C table wled_mirror links.

usage: gen_presets_c.py <presets.json> <out.c>

A missing (or empty-path) JSON gives an empty table. Runs on every badge build (components/wled_mirror/CMakeLists.txt)
and only rewrites <out.c> when its content changes. Stdlib only. The struct layout is wm_entry_t in
components/wled_mirror/include/wled_mirror.h.
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from wp_common import write_if_changed  # noqa: E402

ACTIONS = {"preset": "WM_PRESET", "toggle": "WM_TOGGLE", "off": "WM_OFF", "on": "WM_ON", "bri": "WM_BRI"}
# WLED segment defaults (FX.h DEFAULT_*) for keys a preset leaves out
DEFAULTS = {"fx": 0, "pal": 0, "sx": 128, "ix": 128, "c1": 128, "c2": 128, "c3": 16}


def cstr(s):
    out = []
    for b in s.encode("utf-8"):
        c = chr(b)
        if c in '"\\':
            out.append("\\" + c)
        elif 32 <= b < 127 and c != "?":  # '?' avoids trigraphs
            out.append(c)
        else:
            out.append("\\%03o" % b)  # octal: never swallows a following hex-looking character
    return '"' + "".join(out) + '"'


def u8(v, name, where):
    v = int(v)
    if not 0 <= v <= 255:
        sys.exit(f"gen_presets_c: {where}: {name}={v} is out of 0..255")
    return v


def params_c(p, where):
    f = {k: u8(p.get(k, d), k, where) for k, d in DEFAULTS.items()}
    o = ["true" if p.get(k) else "false" for k in ("o1", "o2", "o3")]
    col = list(p.get("col", [])) + [[0, 0, 0]] * 3
    cols = ", ".join("{%s}" % ", ".join(str(u8(x, "col", where)) for x in (list(c) + [0, 0, 0])[:3]) for c in col[:3])
    vlen = max(0, min(300, int(p.get("vlen", 0))))
    return (f"{{.fx = {f['fx']}, .pal = {f['pal']}, .sx = {f['sx']}, .ix = {f['ix']}, .c1 = {f['c1']}, "
            f".c2 = {f['c2']}, .c3 = {f['c3']}, .o1 = {o[0]}, .o2 = {o[1]}, .o3 = {o[2]}, .col = {{{cols}}}, "
            f".vlen = {vlen}}}")


def main(argv):
    if len(argv) != 3:
        sys.exit(__doc__)
    src, out = argv[1], argv[2]
    entries = []
    if src and os.path.isfile(src):
        with open(src, encoding="utf-8") as f:
            entries = json.load(f).get("entries", [])
    rows = []
    for i, e in enumerate(entries):
        where = f"{os.path.basename(src)} entry {i} ({e.get('menu')!r})"
        if not e.get("menu") or e.get("action") not in ACTIONS:
            sys.exit(f"gen_presets_c: {where}: needs a 'menu' and an 'action' in {sorted(ACTIONS)}")
        value = max(0, min(100, int(e.get("value", 0)))) if e["action"] == "bri" else 0
        params = params_c(e.get("params", {}), where) if e["action"] == "preset" else "{0}"
        rows.append(f"    {{{cstr(e['menu'])}, {ACTIONS[e['action']]}, {value}, {params}}},")
    text = ("// Generated by tools/wled_port/gen_presets_c.py from CONFIG_WLED_PRESETS_FILE. Do not edit.\n"
            '#include "wled_mirror.h"\n\n'
            f"const wm_entry_t wm_entries[] = {{\n" + ("\n".join(rows) + "\n" if rows else "    {0}, // empty table\n")
            + "};\n"
            f"const int wm_entry_count = {len(rows)};\n")
    write_if_changed(os.path.abspath(out), text)


if __name__ == "__main__":
    main(sys.argv)
